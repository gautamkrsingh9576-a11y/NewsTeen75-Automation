create or replace function public.record_article_seen(
  p_article_id text,
  p_dwell_ms integer,
  p_visible_ratio numeric
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;

  if p_dwell_ms < 1000 or p_visible_ratio < 0.5 then
    return;
  end if;

  insert into public.article_seen (
    user_id,
    article_id,
    first_seen_at,
    last_seen_at,
    dwell_ms,
    visible_ratio
  )
  values (
    v_user_id,
    p_article_id,
    now(),
    now(),
    greatest(p_dwell_ms, 1000),
    least(greatest(p_visible_ratio, 0.5), 1)
  )
  on conflict (user_id, article_id)
  do update set
    last_seen_at = excluded.last_seen_at,
    dwell_ms = greatest(public.article_seen.dwell_ms, excluded.dwell_ms),
    visible_ratio = greatest(public.article_seen.visible_ratio, excluded.visible_ratio);
end;
$$;

create or replace function public.merge_guest_seen(
  p_article_ids text[]
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_count integer := 0;
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;

  if p_article_ids is null or cardinality(p_article_ids) = 0 then
    return 0;
  end if;

  insert into public.article_seen (
    user_id,
    article_id,
    first_seen_at,
    last_seen_at,
    dwell_ms,
    visible_ratio
  )
  select
    v_user_id,
    a.id,
    now(),
    now(),
    1000,
    0.5
  from public.news_articles a
  where a.id = any(p_article_ids)
  on conflict (user_id, article_id) do nothing;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

create or replace function public.get_unseen_feed(
  p_category text default null,
  p_limit integer default 20,
  p_before_published_at timestamptz default null,
  p_before_id text default null,
  p_guest_seen_ids text[] default array[]::text[]
)
returns table (
  id text,
  title text,
  summary text,
  image_url text,
  publisher text,
  original_url text,
  category text,
  language text,
  title_hi text,
  summary_hi text,
  title_hinglish text,
  summary_hinglish text,
  published_at timestamptz,
  ingested_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  with candidates as (
    select
      a.*,
      row_number() over (
        partition by coalesce(nullif(a.story_fingerprint, ''), a.id)
        order by a.published_at desc, a.id desc
      ) as story_rank
    from public.news_articles a
    where
      (p_category is null or p_category = '' or a.category = p_category)
      and not (a.id = any(coalesce(p_guest_seen_ids, array[]::text[])))
      and not exists (
        select 1
        from public.article_seen s
        where s.user_id = auth.uid()
          and s.article_id = a.id
      )
      and (
        p_before_published_at is null
        or (a.published_at, a.id) <
           (p_before_published_at, coalesce(p_before_id, ''))
      )
  )
  select
    c.id,
    c.title,
    c.summary,
    c.image_url,
    c.publisher,
    c.original_url,
    c.category,
    c.language,
    c.title_hi,
    c.summary_hi,
    c.title_hinglish,
    c.summary_hinglish,
    c.published_at,
    c.ingested_at
  from candidates c
  where c.story_rank = 1
  order by c.published_at desc, c.id desc
  limit least(greatest(coalesce(p_limit, 20), 1), 50);
$$;

create or replace function public.search_news(
  p_query text,
  p_limit integer default 20,
  p_offset integer default 0
)
returns table (
  id text,
  title text,
  summary text,
  image_url text,
  publisher text,
  original_url text,
  category text,
  language text,
  title_hi text,
  summary_hi text,
  title_hinglish text,
  summary_hinglish text,
  published_at timestamptz,
  ingested_at timestamptz,
  rank real
)
language sql
stable
security definer
set search_path = public
as $$
  with q as (
    select plainto_tsquery('simple', trim(coalesce(p_query, ''))) as query
  )
  select
    a.id,
    a.title,
    a.summary,
    a.image_url,
    a.publisher,
    a.original_url,
    a.category,
    a.language,
    a.title_hi,
    a.summary_hi,
    a.title_hinglish,
    a.summary_hinglish,
    a.published_at,
    a.ingested_at,
    case
      when trim(coalesce(p_query, '')) = '' then 0::real
      else ts_rank(a.search_document, q.query)
    end::real as rank
  from public.news_articles a
  cross join q
  where
    trim(coalesce(p_query, '')) <> ''
    and (
      a.search_document @@ q.query
      or a.title ilike '%' || trim(p_query) || '%'
      or a.summary ilike '%' || trim(p_query) || '%'
      or a.category ilike '%' || trim(p_query) || '%'
      or a.publisher ilike '%' || trim(p_query) || '%'
    )
  order by
    rank desc,
    a.published_at desc,
    a.id desc
  limit least(greatest(coalesce(p_limit, 20), 1), 50)
  offset greatest(coalesce(p_offset, 0), 0);
$$;

create or replace function public.save_article(
  p_article_id text
)
returns void
language sql
security definer
set search_path = public
as $$
  insert into public.saved_articles(user_id, article_id)
  select auth.uid(), p_article_id
  where auth.uid() is not null
  on conflict (user_id, article_id) do nothing;
$$;

create or replace function public.unsave_article(
  p_article_id text
)
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.saved_articles
  where user_id = auth.uid()
    and article_id = p_article_id;
$$;

create or replace function public.list_saved_articles(
  p_limit integer default 50,
  p_offset integer default 0
)
returns table (
  id text,
  title text,
  summary text,
  image_url text,
  publisher text,
  original_url text,
  category text,
  language text,
  title_hi text,
  summary_hi text,
  title_hinglish text,
  summary_hinglish text,
  published_at timestamptz,
  saved_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    a.id,
    a.title,
    a.summary,
    a.image_url,
    a.publisher,
    a.original_url,
    a.category,
    a.language,
    a.title_hi,
    a.summary_hi,
    a.title_hinglish,
    a.summary_hinglish,
    a.published_at,
    s.saved_at
  from public.saved_articles s
  join public.news_articles a on a.id = s.article_id
  where s.user_id = auth.uid()
  order by s.saved_at desc
  limit least(greatest(coalesce(p_limit, 50), 1), 100)
  offset greatest(coalesce(p_offset, 0), 0);
$$;

