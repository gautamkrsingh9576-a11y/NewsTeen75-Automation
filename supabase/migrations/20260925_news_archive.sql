create extension if not exists pg_trgm;

create table if not exists public.news_articles (
  id text primary key,
  provider text not null default 'google_news_rss',
  provider_id text,
  canonical_url text not null unique,
  title text not null,
  summary text not null default '',
  image_url text not null default '',
  publisher text not null default '',
  original_url text not null,
  category text not null default '',
  language text not null default 'en',
  title_hi text,
  summary_hi text,
  title_hinglish text,
  summary_hinglish text,
  published_at timestamptz not null,
  ingested_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  story_fingerprint text,
  search_document tsvector generated always as (
    to_tsvector(
      'simple',
      concat_ws(
        ' ',
        coalesce(title, ''),
        coalesce(summary, ''),
        coalesce(category, ''),
        coalesce(publisher, ''),
        coalesce(title_hi, ''),
        coalesce(summary_hi, ''),
        coalesce(title_hinglish, ''),
        coalesce(summary_hinglish, '')
      )
    )
  ) stored
);

create unique index if not exists news_articles_provider_id_uidx
  on public.news_articles(provider, provider_id)
  where provider_id is not null and provider_id <> '';

create index if not exists news_articles_published_idx
  on public.news_articles(published_at desc, id desc);

create index if not exists news_articles_category_published_idx
  on public.news_articles(category, published_at desc, id desc);

create index if not exists news_articles_search_idx
  on public.news_articles using gin(search_document);

create index if not exists news_articles_title_trgm_idx
  on public.news_articles using gin(title gin_trgm_ops);

create index if not exists news_articles_summary_trgm_idx
  on public.news_articles using gin(summary gin_trgm_ops);

create index if not exists news_articles_publisher_trgm_idx
  on public.news_articles using gin(publisher gin_trgm_ops);

create index if not exists news_articles_story_fingerprint_idx
  on public.news_articles(story_fingerprint)
  where story_fingerprint is not null;

create or replace function public.touch_news_article_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists news_articles_touch_updated_at on public.news_articles;
create trigger news_articles_touch_updated_at
before update on public.news_articles
for each row execute function public.touch_news_article_updated_at();

create table if not exists public.article_seen (
  user_id uuid not null references auth.users(id) on delete cascade,
  article_id text not null references public.news_articles(id) on delete cascade,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  dwell_ms integer not null default 1000 check (dwell_ms >= 1000),
  visible_ratio numeric(4,3) not null default 0.5
    check (visible_ratio >= 0.5 and visible_ratio <= 1),
  primary key (user_id, article_id)
);

create index if not exists article_seen_user_time_idx
  on public.article_seen(user_id, last_seen_at desc);

create table if not exists public.saved_articles (
  user_id uuid not null references auth.users(id) on delete cascade,
  article_id text not null references public.news_articles(id) on delete cascade,
  saved_at timestamptz not null default now(),
  primary key (user_id, article_id)
);

create index if not exists saved_articles_user_time_idx
  on public.saved_articles(user_id, saved_at desc);

create table if not exists public.news_ingestion_runs (
  id bigint generated by default as identity primary key,
  ran_at timestamptz not null default now(),
  status text not null check (status in ('success', 'error')),
  fetched_count integer not null default 0,
  feed_count integer not null default 0,
  archived_count integer not null default 0,
  error_message text
);

